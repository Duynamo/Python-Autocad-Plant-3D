def init_db():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    # 1. Bảng metric_bolt_standards
    cur.execute("DROP TABLE IF EXISTS metric_bolt_standards;")
    cur.execute("""
    CREATE TABLE metric_bolt_standards (
        standard TEXT NOT NULL,
        size TEXT PRIMARY KEY,
        nominal_dia REAL NOT NULL,
        pitch REAL NOT NULL,
        s REAL NOT NULL,
        e REAL NOT NULL,
        m REAL NOT NULL,
        k REAL NOT NULL,
        washer_t REAL NOT NULL,
        washer_od REAL NOT NULL
    );
    """)

    cur.executemany("""
    INSERT INTO metric_bolt_standards (standard, size, nominal_dia, pitch, s, e, m, k, washer_t, washer_od)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, METRIC_BOLT_STANDARDS)

    # 2. Bảng jis_b1217_flange_bolts
    cur.execute("DROP TABLE IF EXISTS jis_b1217_flange_bolts;")
    cur.execute("""
    CREATE TABLE jis_b1217_flange_bolts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        standard TEXT NOT NULL,
        flange_std TEXT NOT NULL,
        rating TEXT NOT NULL,
        dn INTEGER NOT NULL,
        bolt_size TEXT NOT NULL,
        bolt_count INTEGER NOT NULL,
        l REAL NOT NULL,
        b REAL NOT NULL,
        lt REAL NOT NULL,
        bt REAL NOT NULL,
        tg REAL NOT NULL,
        CONSTRAINT uq_bolt_flange UNIQUE (standard, flange_std, rating, dn)
    );
    """)
    cur.execute("CREATE INDEX IF NOT EXISTS idx_b1217_lookup ON jis_b1217_flange_bolts(standard, flange_std, rating, dn);")

    cur.executemany("""
    INSERT OR REPLACE INTO jis_b1217_flange_bolts (standard, flange_std, rating, dn, bolt_size, bolt_count, l, b, lt, bt, tg)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, JIS_B1217_RAW_DATA)

    conn.commit()
    conn.close()

    print(f"[OK] Database initialized successfully at: {DB_PATH}")
    print(f"[OK] Seeded {len(METRIC_BOLT_STANDARDS)} metric bolt specs with standard='JIS_B_1180'.")
    print(f"[OK] Seeded {len(JIS_B1217_RAW_DATA)} bolt pairing rows with standard='JIS_B_1217', flange_std='JIS_B_2220'.")

    # 3. Sinh file jis_b1217_dataset.py
    generate_python_dataset()


